import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {join} from 'node:path';

// Keep the checked-in, route-specific HTML shells in sync with index.html
// and app4.js. Run: node scripts/generate-seo-pages.mjs
// The preview stays noindex until the approved live launch.
const index=await readFile('index.html','utf8');
const app=await readFile('app4.js','utf8');
const start=app.indexOf('const seoMeta={');
const end=app.indexOf('\n};',start);
if(start<0||end<0)throw new Error('seoMeta not found');
const entries=[...app.slice(start,end).matchAll(/'(\/[^']*)':\{title:'([^']+)',description:'([^']+)',canonical:'([^']+)'\}/g)];
if(entries.length<20)throw new Error('Too few SEO routes: '+entries.length);
const origin='https://www.autismassessmentsfarnham.co.uk';
const escape=s=>s.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
const serviceRoutes=new Set(['/adult-autism-assessment','/adult-adhd-assessment','/combined-adult-autism-adhd-assessment','/child-autism-assessment','/child-adhd-assessment','/combined-child-autism-adhd-assessment']);
const originalBrandRoutes=new Set(['/','/adult-assessments','/child-young-person-assessments',...serviceRoutes,'/fees','/contact','/adult-pre-booking','/child-pre-booking']);
const areas=['Farnham','Guildford','Godalming','Aldershot','Farnborough','Fleet','Haslemere','Woking','Surrey','Hampshire'];
const logo='https://static.wixstatic.com/media/1e4c48_6e4874f00b294c42add7876f8644f89b~mv2.png';
const replacement=(s,re,v,label)=>{const o=s.replace(re,v);if(o===s)throw new Error('Not found: '+label);return o};
for(const m of entries){
  const [,path,title,desc,canonical]=m;
  if(path==='/')continue;
  const speech=path==='/ehcp-expert-witness-reports';
  const brand=speech?'speech':originalBrandRoutes.has(path)?'legacy':'compact';
  const heading=title.split(' | ')[0];
  const type=speech?'ProfessionalService':'MedicalClinic';
  const name=speech?'Speech Therapy Farnham':'Autism & ADHD Assessments Farnham';
  const email=speech?'speechtherapyfarnham@gmail.com':'lisa@autismassessmentsfarnham.co.uk';
  const schema={'@context':'https://schema.org','@graph':[
    {'@type':type,'@id':origin+(speech?'/ehcp-expert-witness-reports#service':'/#clinic'),name,url:origin+(speech?path:'/'),telephone:'+44 7387 697876',email,address:{'@type':'PostalAddress',streetAddress:'The Annexe, 3 Leigh Lane',addressLocality:'Farnham',addressRegion:'Surrey',postalCode:'GU9 8HP',addressCountry:'GB'},areaServed:areas,...(speech?{}:{logo})},
    {'@type':'WebSite','@id':origin+'/#website',url:origin+'/',name:'Autism & ADHD Assessments Farnham'},
    {'@type':'WebPage','@id':origin+canonical+'#webpage',url:origin+canonical,name:title,description:desc,isPartOf:{'@id':origin+'/#website'}},
    {'@type':'BreadcrumbList',itemListElement:[{'@type':'ListItem',position:1,name:'Home',item:origin+'/'},{'@type':'ListItem',position:2,name:heading,item:origin+canonical}]},
    ...(serviceRoutes.has(path)?[{'@type':'Service',name:heading,description:desc,provider:{'@id':origin+'/#clinic'},areaServed:areas,url:origin+path}]:[])
  ]};
  let html=index;
  html=replacement(html,/<meta name="description" content="[^"]*">/, '<meta name="description" content="'+escape(desc)+'">','meta description');
  for(const [prop,value] of [['og:title',title],['og:description',desc],['og:url',origin+canonical],['og:site_name',name]]){
    html=replacement(html,new RegExp('<meta property="'+prop+'" content="[^"]*">'),'<meta property="'+prop+'" content="'+escape(value)+'">',prop);
  }
  html=replacement(html,/<link rel="canonical" href="[^"]*">/,'<link rel="canonical" href="'+origin+canonical+'">','canonical');
  html=replacement(html,/<title>[^<]*<\/title>/,'<title>'+escape(title)+'</title>','title');
  html=replacement(html,/<script id="seo-schema" type="application\/ld\+json">[\s\S]*?<\/script>/,'<script id="seo-schema" type="application/ld+json">'+JSON.stringify(schema)+'</script>','schema');
  html=replacement(html,/<body data-brand="legacy" data-page="home" data-review-path="\/">/,'<body data-brand="'+brand+'" data-page="inner" data-review-path="'+escape(path)+'">','body route');
  const routeCTA=speech?'<a class="btn" href="mailto:speechtherapyfarnham@gmail.com">Email Speech Therapy Farnham</a>':'<a class="btn" href="/contact">Contact the clinic</a>';
  const main='<main id="app"><section class="page-hero"><div class="eyebrow">'+escape(name)+'</div><h1>'+escape(heading)+'</h1><p>'+escape(desc)+'</p><div class="hero-actions">'+routeCTA+'</div></section></main>';
  html=replacement(html,/<main id="app">[\s\S]*?<\/main>/,main,'main');
  // Search engines and people without JS receive useful real content;
  // app4.js replaces the fallback with the full approved page after loading.
  html='<!-- Generated by scripts/generate-seo-pages.mjs; do not hand-edit. -->\n'+html;
  const folder=join('.',path.slice(1));
  await mkdir(folder,{recursive:true});
  await writeFile(join(folder,'index.html'),html,'utf8');
}
console.log('Created '+(entries.length-1)+' canonical SEO route pages; preview remains noindex.');
